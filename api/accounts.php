declare(strict_types=1);

namespace Accounts;

const USER_PATTERN = '#^[a-z0-9][a-z0-9._-]{0,63}$#';
const ROLES = ['admin', 'editor'];

function templatePath(): string
{
    return __DIR__ . '/config/accounts.php';
}

function realPath(): string
{
    return __DIR__ . '/config/accounts.local.php';
}

/** The git-ignored real store wins over the template. */
function storePath(): string
{
    return is_file(realPath()) ? realPath() : templatePath();
}

/** Normalize the accounts map (numbered arrays, missing roles). Never leaks file errors to the caller. */
function all(): array
{
    try {
        $accounts = require storePath();
    } catch (\Throwable) {
        return [];
    }
    if (!is_array($accounts)) {
        return [];
    }
    $clean = [];
    foreach ($accounts as $user => $record) {
        if (!is_string($user) || !is_array($record)) {
            continue;
        }
        $role = in_array($record['role'] ?? '', ROLES, true) ? $record['role'] : 'editor';
        $hash = is_string($record['passwordHash'] ?? null) ? $record['passwordHash'] : null;
        if ($hash === null) {
            continue;
        }
        $email = isset($record['email']) && is_string($record['email']) ? $record['email'] : '';
        $clean[$user] = ['role' => $role, 'passwordHash' => $hash, 'email' => $email];
    }
    // Legacy migration: the old single-password hash becomes the 'admin' account.
    if ($clean === [] && is_file(__DIR__ . '/config/auth.local.php')) {
        try {
            $legacy = require __DIR__ . '/config/auth.local.php';
            $hash = is_array($legacy) && is_string($legacy['passwordHash'] ?? null) ? $legacy['passwordHash'] : null;
            if ($hash !== null) {
                $clean['admin'] = ['role' => 'admin', 'passwordHash' => $hash];
            }
        } catch (\Throwable) {
        }
    }
    return $clean;
}

/** Persist atomically about as defensively as Store\write does. */
function save(array $accounts): void
{
    $target = realPath();
    if (!is_dir(__DIR__ . '/config')) {
        @mkdir(__DIR__ . '/config', 0775, true);
    }
    $php = "<?php\n\n/* Generated by Schmarrn account management. Argon2id hashes only — NEVER plaintext. */\n\ndeclare(strict_types=1);\n\nreturn ";
    $php .= var_export($accounts, true);
    $php .= ";\n";
    $tmp = $target . '.' . bin2hex(random_bytes(6)) . '.tmp';
    if (file_put_contents($tmp, $php) === false || !rename($tmp, $target)) {
        @unlink($tmp);
        \Router\refuse(500, 'The account tin is sealed shut — write failed.');
    }
    // The store is a PHP file, so opcache may serve the stale compiled copy
    // to the next request on this process (same-second writes defeat mtime
    // validation) — a freshly created account then can't log in. Invalidate
    // immediately; a no-op when opcache is absent.
    if (function_exists('opcache_invalidate')) {
        @opcache_invalidate($target, true);
    }
}

function assertKnownRole(string $role): void
{
    if (!in_array($role, ROLES, true)) {
        \Router\refuse(400, "Unknown role: {$role}");
    }
}

function add(string $user, string $hash, string $role, string $email = ''): void
{
    if (!is_string($user) || preg_match(USER_PATTERN, $user) !== 1) {
        \Router\refuse(400, 'That username falls apart in the batter.');
    }
    assertKnownRole($role);
    if ($email !== '' && filter_var($email, FILTER_VALIDATE_EMAIL) === false) {
        \Router\refuse(400, 'That email is half-baked — no proper address in the dough.');
    }
    $accounts = all();
    if (isset($accounts[$user])) {
        \Router\refuse(409, "Account exists: {$user}");
    }
    $accounts[$user] = ['role' => $role, 'passwordHash' => $hash, 'email' => $email];
    save($accounts);
}

function setEmail(string $user, string $email): void
{
    if ($email !== '' && filter_var($email, FILTER_VALIDATE_EMAIL) === false) {
        \Router\refuse(400, 'That email is half-baked — no proper address in the dough.');
    }
    $accounts = all();
    if (!isset($accounts[$user])) {
        \Router\refuse(404, "No account: {$user}");
    }
    $accounts[$user]['email'] = $email;
    save($accounts);
}

function remove(string $user): void
{
    $accounts = all();
    if (!isset($accounts[$user])) {
        \Router\refuse(404, "No account: {$user}");
    }
    unset($accounts[$user]);
    save($accounts);
}

function setRole(string $user, string $role): void
{
    assertKnownRole($role);
    $accounts = all();
    if (!isset($accounts[$user])) {
        \Router\refuse(404, "No account: {$user}");
    }
    $accounts[$user]['role'] = $role;
    save($accounts);
}

function setHash(string $user, string $hash): void
{
    $accounts = all();
    if (!isset($accounts[$user])) {
        \Router\refuse(404, "No account: {$user}");
    }
    $accounts[$user]['passwordHash'] = $hash;
    save($accounts);
}

// ——— one-time password-reset tokens (stored in the file cache, single-use, TTL'd) ———

function tokenDir(): string
{
    $dir = __DIR__ . '/cache/tokens';
    if (!is_dir($dir)) {
        @mkdir($dir, 0775, true);
    }
    return $dir;
}

/** Mails a reset token (hashed at rest) and returns the slicer it cut the token file with. */
function issueMailToken(string $user, string $to, int $ttl = 7200): void
{
    $token = bin2hex(random_bytes(24));
    $record = ['t' => hash('sha256', $token), 'user' => $user, 'exp' => time() + $ttl];
    $file = tokenDir() . '/' . hash('sha256', $user) . '.json';
    $tmp = $file . '.tmp';
    if (file_put_contents($tmp, json_encode($record)) === false || !rename($tmp, $file)) {
        @unlink($tmp);
        \Router\refuse(500, 'The reset token slipped off the tray — storage failed.');
    }
    \Mail\send($to, "Schmarrn password reset ({$user})",
        "Someone asked for a Schmarrn password reset for the account '{$user}'.\n\n"
        . "Reset token (valid 2 h, single use):\n\n    {$token}\n\n"
        . "Didn't ask for this? Ignore and shoo.");
}

/** Consumes a token: right user, not expired, still on file. Single use — it eats itself. */
function takeMailToken(string $user, string $token): void
{
    $file = tokenDir() . '/' . hash('sha256', $user) . '.json';
    $record = $file !== '' && is_file($file) ? json_decode((string)file_get_contents($file), true) : null;
    @unlink($file); // single use: gone the moment someone presents any ticket for this user
    $ok = is_array($record)
        && is_string($record['t'] ?? null)
        && ($record['user'] ?? '') === $user
        && ($record['exp'] ?? 0) >= time()
        && hash_equals($record['t'], hash('sha256', $token));
    if (!$ok) {
        \Router\refuse(401, 'That reset token is stale dough — expired, eaten, or never baked.');
    }
}
